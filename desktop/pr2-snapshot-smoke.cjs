// Synthetic fixture only; exercise the real secure custom-origin IPC/PDF capture on Windows.
const {app,BrowserWindow,ipcMain,protocol}=require('electron');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),os=require('node:os');
protocol.registerSchemesAsPrivileged([{scheme:'banksetu',privileges:{standard:true,secure:true,supportFetchAPI:true,corsEnabled:true}}]);
const scratch=fs.mkdtempSync(path.join(os.tmpdir(),'banksetu-pr2-snapshot-'));app.setPath('userData',scratch);
let window;
app.whenReady().then(async()=>{
 try{
  const root=path.resolve(__dirname,'../dist');
  // Synthetic approved-source fixture generated by the browser test. Inline Vite styles remain;
  // replace dev URLs with packaged resources so this checks the isolated banksetu session handler.
  const css=fs.readdirSync(path.join(root,'assets')).filter(n=>n.endsWith('.css')).map(n=>`<link rel="stylesheet" href="banksetu://app/assets/${n}">`).join('');
  const fixtures={};for(const bank of ['assam','union']){let html=fs.readFileSync(path.resolve(__dirname,`../test-evidence/pr2-${bank}-source.html`),'utf8');html=html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'').replace('</head>',css+'</head>');fixtures[bank]=html;}
  const resource=require('./app-protocol.cjs').createAppProtocol(root);
  protocol.handle('banksetu',request=>{const bank=new URL(request.url).pathname.slice(1);return fixtures[bank]?new Response(fixtures[bank],{headers:{'Content-Type':'text/html'}}):resource(request);});
  require('./pr2-ipc.cjs').installPr2({app,ipcMain,BrowserWindow,getWindow:()=>window,authorize:scope=>assert.equal(scope,'synthetic:user:tenant:connection'),trusted:event=>{assert.equal(event.sender,window.webContents);assert.equal(event.senderFrame,window.webContents.mainFrame);assert.ok(event.senderFrame.url.startsWith('banksetu://app/'));}});
  window=new BrowserWindow({show:false,webPreferences:{preload:path.join(__dirname,'preload.cjs'),contextIsolation:true,nodeIntegration:false,sandbox:true}});
  for(const bank of ['assam','union']){
   await window.loadURL('banksetu://app/'+bank);
   const result=await window.webContents.executeJavaScript('window.bankSetuPr2.prepare("synthetic:user:tenant:connection")');
   const pdf=Buffer.from(result.pdf,'base64');assert.equal(pdf.subarray(0,5).toString(),'%PDF-');assert.ok(pdf.length>5000);assert.match(result.id,/^[a-f0-9-]{36}$/);
   console.log('PASS: Windows secure IPC freezes '+bank+' layout with packaged resources into a PDF.');
  }
  window.destroy();app.exit(0);
 }catch(error){console.error(error);app.exit(1);}
});
setTimeout(()=>{console.error('PR2 snapshot smoke timed out');app.exit(1);},60000).unref();
